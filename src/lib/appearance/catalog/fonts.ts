const FONT_BY_ID = new Map<string, CatalogFont>();
const FONT_BY_FAMILY = new Map<string, CatalogFont>();

for (const f of CATALOG_FONTS) {
  FONT_BY_ID.set(f.id.toLowerCase(), f);
  FONT_BY_FAMILY.set(f.family.toLowerCase(), f);
}

export function findCatalogFont(idOrFamily?: string | null): CatalogFont | null {
  if (!idOrFamily || typeof idOrFamily !== 'string') return null;
  const clean = idOrFamily.trim().toLowerCase();
  if (!clean) return null;
  return FONT_BY_ID.get(clean) || FONT_BY_FAMILY.get(clean) || null;
}

export function isFontAllowedForRole(font: CatalogFont, role: FontRoleFit): boolean {
  if (role === 'B' && font.excludeFromBio) return false;
  if (role === 'B' && font.category === 'script') return false;
  return font.roles.includes(role);
}

export function clampWeightToFont(font: CatalogFont, weight: number): number {
  if (font.weights.includes(weight)) return weight;
  let nearest = font.weights[0];
  let minDiff = Infinity;
  for (const w of font.weights) {
    const diff = Math.abs(w - weight);
    if (diff < minDiff) {
      minDiff = diff;
      nearest = w;
    }
  }
  return nearest;
}

export function getFreeFallbackFont(category: FontCategoryV2, role: FontRoleFit): CatalogFont {
  if (role === 'B') {
    return category === 'serif'
      ? FONT_BY_ID.get('newsreader')!
      : FONT_BY_ID.get('inter')!;
  }
  if (category === 'serif') return FONT_BY_ID.get('merriweather')!;
  if (category === 'mono') return FONT_BY_ID.get('jetbrains-mono')!;
  if (category === 'display') return FONT_BY_ID.get('space-grotesk')!;
  return FONT_BY_ID.get('plus-jakarta')!;
}

export function getFontStackWithFallback(font: CatalogFont): string {
  return font.cssFamily;
}
