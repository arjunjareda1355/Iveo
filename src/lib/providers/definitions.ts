export function getProviderDefinition(id: string | null | undefined): ProviderDefinition {
  const key = String(id || 'generic').toLowerCase().trim() as ProviderId;
  return PROVIDER_REGISTRY[key] || PROVIDER_REGISTRY.generic;
}

export function getProviderKindDefinition(
  providerId: string | null | undefined,
  subtype?: string | null
) {
  const def = getProviderDefinition(providerId);
  const subKey = String(subtype || def.defaultKind).toLowerCase().trim();
  return def.kinds[subKey] || def.kinds[def.defaultKind] || Object.values(def.kinds)[0];
}

export function getProviderDefaultButtonText(
  providerId: string | null | undefined,
  subtype?: string | null
): string {
  return getProviderKindDefinition(providerId, subtype)?.defaultButtonText || 'Open';
}

export function listPlatformProviders(): ProviderDefinition[] {
  return Object.values(PROVIDER_REGISTRY).filter((p) => p.id !== 'generic');
}
