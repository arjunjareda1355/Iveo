export const DEFAULT_AVATAR_LIST: readonly DefaultAvatar[] = DEFAULT_AVATARS.map(
  (url, index) => {
    const id = `default_avatar_${String(index + 1).padStart(2, '0')}`;
    return {
      id,
      url,
      name: `Avatar ${index + 1}`,
    };
  }
);

const AVATAR_BY_ID = new Map<string, DefaultAvatar>(
  DEFAULT_AVATAR_LIST.map((a) => [a.id, a])
);

const AVATAR_BY_URL = new Map<string, DefaultAvatar>(
  DEFAULT_AVATAR_LIST.map((a) => [a.url, a])
);

export function getDefaultAvatarById(id: string | null | undefined): DefaultAvatar | undefined {
  if (!id) return undefined;
  return AVATAR_BY_ID.get(id);
}

export function getDefaultAvatarByUrl(url: string | null | undefined): DefaultAvatar | undefined {
  if (!url) return undefined;
  const clean = url.trim();
  return AVATAR_BY_URL.get(clean);
}

export function isDefaultAvatarUrl(url: string | null | undefined): boolean {
  if (!url) return false;
  return AVATAR_BY_URL.has(url.trim());
}
